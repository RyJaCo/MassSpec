// Generates examples/demo_pr_matrix.tsv and js/demo.js: a SIMULATED DIA-NN style
// pr_matrix for GFP (P42212) digested with trypsin. Intensities are invented to look
// like real data (several orders of magnitude apart); they are not measurements.
// Run: node tools/make-demo.js
'use strict';
const fs = require('fs');
const path = require('path');
const D = require('../js/digest.js');

const FASTA = '>sp|P42212|GFP_AEQVI Green fluorescent protein OS=Aequorea victoria OX=6100 GN=GFP PE=1 SV=1\n' +
  'MSKGEELFTGVVPILVELDGDVNGHKFSVSGEGEGDATYGKLTLKFICTTGKLPVPWPTLVTTFSYGVQCFSRYPDHMKQHDFFKSAMPEGYVQERTIFFKDDGNYKTRAEVKFEGDTLVNRIELKGIDFKEDGNILGHKLEYNYNSHNVYIMADKQKNGIKVNFKIRHNIEDGSVQLADHYQQNTPIGDGPVLLPDNHYLSTQSALSKDPNEKRDHMVLLEFVTAAGITHGMDELYK';
const protein = D.parseFasta(FASTA)[0].seq;

// Small deterministic PRNG so the demo file is reproducible.
let s = 7;
const rnd = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
const gauss = () => Math.sqrt(-2 * Math.log(rnd() + 1e-12)) * Math.cos(2 * Math.PI * rnd());

const KD = { A: 1.8, R: -4.5, N: -3.5, D: -3.5, C: 2.5, Q: -3.5, E: -3.5, G: -0.4, H: -3.2, I: 4.5,
  L: 3.8, K: -3.9, M: 1.9, F: 2.8, P: -1.6, S: -0.8, T: -0.7, W: -0.9, Y: -1.3, V: 4.2 };
const gravy = (p) => [...p].reduce((a, c) => a + (KD[c] || 0), 0) / p.length;

const { peptides } = D.digest(protein, { enzymes: ['trypsin'], missed: 1, minLen: 1, maxLen: 999, metLoss: true });
const runs = ['/data/2026-10/GFP_digest_rep1.raw', '/data/2026-10/GFP_digest_rep2.raw', '/data/2026-10/GFP_digest_rep3.raw'];
const rows = [];
for (const p of peptides) {
  const L = p.length;
  if (L < 7 || L > 30) continue;                       // DIA-NN default library range
  if (p.start === 1 && !p.nTermMetLoss) continue;      // initiator Met is removed in vivo
  if (p.missed > 0 && rnd() > 0.3) continue;           // only some missed cleavages are seen
  let logI = 6.6 + 0.4 * gravy(p.seq) + 0.55 * gauss();
  if (p.missed) logI -= 1.2;
  if (L > 22) logI -= 0.6;
  if (/M/.test(p.seq)) logI -= 0.3;                    // part of the signal lost to Met oxidation
  if (logI < 4.9) continue;                            // below the limit of detection
  const charges = L >= 12 && rnd() < 0.7 ? [2, 3] : [2];
  charges.forEach((z, zi) => {
    const share = charges.length === 1 ? 1 : zi === 0 ? 0.75 : 0.25;
    const vals = runs.map(() => {
      const v = Math.pow(10, logI + 0.07 * gauss()) * share;
      return v < 3e4 && rnd() < 0.5 ? '' : v.toPrecision(6);
    });
    rows.push({ p, z, vals });
  });
}
// A few precursors from another protein, to show that only matching peptides are used.
const other = [['LVNELTEFAK', 2], ['YLYEIAR', 2], ['HPEYAVSVLLR', 2], ['AEFVEVTK', 2]];
const header = ['Protein.Group', 'Protein.Ids', 'Protein.Names', 'Genes', 'First.Protein.Description',
  'Proteotypic', 'Stripped.Sequence', 'Modified.Sequence', 'Precursor.Charge', 'Precursor.Id', ...runs];
const lines = [header.join('\t')];
for (const { p, z, vals } of rows) {
  const mod = p.seq.replace(/C/g, 'C(UniMod:4)');
  lines.push(['P42212', 'P42212', 'GFP_AEQVI', 'GFP', 'Green fluorescent protein', 1, p.seq, mod, z, mod + z, ...vals].join('\t'));
}
for (const [seq, z] of other) {
  const vals = runs.map(() => Math.pow(10, 7 + 0.3 * gauss()).toPrecision(6));
  lines.push(['P02769', 'P02769', 'ALBU_BOVIN', 'ALB', 'Albumin', 1, seq, seq, z, seq + z, ...vals].join('\t'));
}
const tsv = lines.join('\n') + '\n';
fs.writeFileSync(path.join(__dirname, '..', 'examples', 'demo_pr_matrix.tsv'), tsv);
fs.writeFileSync(path.join(__dirname, '..', 'examples', 'GFP_P42212.fasta'), FASTA + '\n');
fs.writeFileSync(path.join(__dirname, '..', 'js', 'demo.js'),
  '// Generated by tools/make-demo.js. SIMULATED data for teaching; not real measurements.\n' +
  'window.DEMO = ' + JSON.stringify({ fasta: FASTA, prMatrix: tsv, prMatrixName: 'demo_pr_matrix.tsv (simulated)' }, null, 0) + ';\n');
console.log('rows', rows.length + other.length);
