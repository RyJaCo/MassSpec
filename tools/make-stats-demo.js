// Generates the SIMULATED example tables for the Stats Test Advisor:
//   examples/stats_demo_experiment.csv  long format: treatment × genotype, several kinds of outcome
//   examples/stats_demo_paired.csv      wide format: the same patients at three time points
// and js/stats-demo.js, which embeds both so the page works when opened from disk.
// Run: node tools/make-stats-demo.js
'use strict';
const fs = require('fs');
const path = require('path');

let s = 20261103;
const rnd = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
const gauss = () => Math.sqrt(-2 * Math.log(rnd() + 1e-12)) * Math.cos(2 * Math.PI * rnd());
function poisson(l) { let L = Math.exp(-l), k = 0, p = 1; do { k++; p *= rnd(); } while (p > L); return k - 1; }
const r = (v, d) => Number(v.toPrecision(d || 5));

// --- long-format experiment
const treatments = ['Vehicle', 'Low dose', 'High dose', 'Inhibitor'];
const genotypes = ['WT', 'KO'];
const effX = { Vehicle: 0, 'Low dose': 0.5, 'High dose': 1.4, Inhibitor: -0.2 };     // log2 fold changes
const effRatio = { Vehicle: 0, 'Low dose': 0.4, 'High dose': 1.1, Inhibitor: -0.8 };
const effViab = { Vehicle: 92, 'Low dose': 88, 'High dose': 71, Inhibitor: 90 };
const effFoci = { Vehicle: 2, 'Low dose': 3, 'High dose': 7, Inhibitor: 1.5 };
const rows = [['Sample', 'Mouse', 'Treatment', 'Genotype', 'Injection', 'ProteinX_intensity', 'ProteinY_intensity', 'Phospho_total_ratio', 'Viable_cells_pct', 'Foci_count', 'Body_weight_g', 'Histology_score', 'Responder']];
let sample = 0, mouse = 0;
for (const g of genotypes) {
  for (const t of treatments) {
    for (let m = 0; m < 5; m++) {
      mouse++;
      const mouseEff = gauss() * 0.35;
      const ko = g === 'KO' ? -0.6 : 0;
      const inter = g === 'KO' && t === 'High dose' ? -0.7 : 0;
      const logX = 22 + effX[t] + ko + inter + mouseEff;
      const ratio = Math.pow(2, effRatio[t] + (g === 'KO' ? 0.2 : 0) + gauss() * 0.45);
      const viab = Math.max(1, Math.min(99.5, effViab[t] + (g === 'KO' ? -4 : 0) + gauss() * 4));
      const foci = poisson(effFoci[t] * (g === 'KO' ? 1.3 : 1));
      const weight = 24 + (g === 'KO' ? -1.5 : 0) + gauss() * 1.6;
      const score = Math.max(0, Math.min(3, Math.round((effX[t] + gauss() * 0.8) * 1.2 + 1)));
      const responder = rnd() < (t === 'High dose' ? 0.8 : t === 'Low dose' ? 0.45 : 0.2) ? 'Yes' : 'No';
      // two injections (technical replicates) of each mouse for the MS columns
      for (let inj = 1; inj <= 2; inj++) {
        sample++;
        const lx = logX + gauss() * 0.12;
        const ly = 0.8 * (logX - 22) + 20 + gauss() * 0.35 + gauss() * 0.1;
        rows.push([`S${String(sample).padStart(3, '0')}`, `M${String(mouse).padStart(2, '0')}`, t, g, inj,
          Math.round(Math.pow(2, lx)), Math.round(Math.pow(2, ly)), r(ratio, 4), r(viab, 3), foci, r(weight, 3), score, responder]);
      }
    }
  }
}
const csv = rows.map((x) => x.map((v) => (/[,"]/.test(String(v)) ? `"${v}"` : v)).join(',')).join('\n') + '\n';

// --- wide paired: cytokine level in patients before, during and after treatment (log-normal, paired)
const paired = [['Patient', 'Baseline', 'Week_4', 'Week_12']];
for (let p = 1; p <= 12; p++) {
  const base = 3.2 + gauss() * 0.8;
  paired.push([`P${String(p).padStart(2, '0')}`, r(Math.exp(base + gauss() * 0.2), 4), r(Math.exp(base - 0.45 + gauss() * 0.25), 4), r(Math.exp(base - 0.7 + gauss() * 0.3), 4)]);
}
const csv2 = paired.map((x) => x.join(',')).join('\n') + '\n';

const root = path.join(__dirname, '..');
fs.writeFileSync(path.join(root, 'examples/stats_demo_experiment.csv'), csv);
fs.writeFileSync(path.join(root, 'examples/stats_demo_paired.csv'), csv2);
fs.writeFileSync(path.join(root, 'js/stats-demo.js'),
  '// Generated by tools/make-stats-demo.js. SIMULATED data for teaching; not real measurements.\n' +
  'window.STATS_DEMO = ' + JSON.stringify({ experiment: csv, paired: csv2 }) + ';\n');
console.log(`wrote ${rows.length - 1} + ${paired.length - 1} rows`);
